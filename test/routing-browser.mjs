import {createRequire} from 'node:module';
const root=process.cwd();
const require=createRequire(root+'/package.json');const {chromium}=require('playwright');
const {openDb,upsertUser,createThread,addMessage}=await import(root+'/server/db.ts');
const {buildApp}=await import(root+'/server/routes.ts');
const db=openDb(':memory:');for(const [name,t] of [['예제사용자','a'],['예제동료','b'],['서연','c']])upsertUser(db,name,t);
const thread=createThread(db,'API 변경 사항 검토','예제사용자');
addMessage(db,{threadId:thread.id,author:'예제사용자',authorType:'human',kind:'text',body:'@예제동료 로그인 API 변경 사항을 같이 확인해 주세요.'});
addMessage(db,{threadId:thread.id,author:'예제동료',authorType:'agent',kind:'text',body:'변경 사항을 확인했어요. 응답 형식과 오류 처리 방식을 정리하고 있습니다.\n검토가 끝나면 결정이 필요한 부분만 알려드릴게요.'});
const srv=buildApp(db).listen(0);await new Promise(r=>srv.once('listening',r));const base=`http://127.0.0.1:${srv.address().port}`;
const browser=await chromium.launch({channel:'chrome',headless:true});
try {
 const page=await browser.newPage();
 await page.addInitScript(id=>{localStorage.setItem('token','a');localStorage.setItem(`mentionTarget:예제사용자:${id}`,'예제사용자');},thread.id);
 await page.goto(base);await page.getByRole('button',{name:/API 변경 사항 검토/}).click();
 const send=async(text)=>{
  await page.locator('#input').fill(text);
  const response=page.waitForResponse(r=>r.url().endsWith('/messages')&&r.request().method()==='POST');
  await page.locator('#send').click();return (await response).json();
 };
 await page.locator('#mentionTargetText').filter({hasText:'예제동료'}).waitFor();
 if(await page.locator('#routePeople label').filter({hasText:'서연'}).count())throw Error('Nonparticipant shown');
 const follow=await send('다시 확인해줘');if(follow.body!=='@예제동료 다시 확인해줘')throw Error('followup target');
 const direct=await send('제가 확인할게요');if(direct.body!=='제가 확인할게요')throw Error('direct reply');
 await page.locator('[data-route-mode=direct]').click();
 const plain=await send('다시 확인해줘');if(plain.body!=='다시 확인해줘')throw Error('manual direct');
 await page.locator('#input').fill('@성');
 await page.locator('#mentionMenu [role=option]').first().click();
 if(await page.locator('[data-route-mode=direct]').getAttribute('aria-pressed')!=='true')throw Error('mention selection changed mode');
 const targeted=await send('@서연 @예제동료 알림 오나요?');
 if(!targeted.direct)throw Error('direct mention lost');
 if(await page.locator('[data-route-mode=direct]').getAttribute('aria-pressed')!=='true')throw Error('direct mode reset');
 await page.locator('[data-route-mode=auto]').click();
 const both=await send('@서연 @예제동료 같이 확인해주세요');
 await page.waitForFunction(()=>document.querySelector('[data-route-mode=auto]').getAttribute('aria-pressed')==='true');
 await page.locator('#routePeople label').filter({hasText:'서연'}).first().waitFor({state:'attached'});
 const group=await send('다시 확인해줘');if(group.body!=='@서연 @예제동료 다시 확인해줘')throw Error('group');
 const switchTo=await send('서연님 확인해주세요');if(switchTo.body!=='@서연 서연님 확인해주세요')throw Error('named target');
 await page.locator('[data-route-mode=direct]').click();await page.reload();
 await page.getByRole('button',{name:/API 변경 사항 검토/}).click();
 if(await page.locator('[data-route-mode=direct]').getAttribute('aria-pressed')!=='true')throw Error('persistence');
 await page.locator('[data-route-mode=agents]').click();
 await page.locator('#routePeople input[value=예제동료]').check();
 await page.locator('#routePeople input[value=서연]').check();
 const checked=await send('한번 더 확인');if(!checked.body.includes('@서연')||!checked.body.includes('@예제동료'))throw Error('checkbox multiple targets');
 await page.locator('#privateToggle').click();const own=await send('이 내용을 정리해 줘');
 if(own.body!=='@예제사용자 이 내용을 정리해 줘'||own.privateTo!=='예제사용자')throw Error('private routing');
 await page.screenshot({path:'/tmp/messenger-routing-ui.png'});
 console.log('PASS: follow-up, multiple targets, named switch, direct reply, reload persistence, private routing.');
}finally{await browser.close();srv.closeAllConnections();srv.close();db.close();}
